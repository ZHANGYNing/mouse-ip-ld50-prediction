"""Whole-pool residual screening, followed by internal CV of each retained cohort.

Five arms: no deletion, or deletion at 5/10/20/30-fold historical OOF error.
All use KFold(n_splits=5, shuffle=True, random_state=42) and seed=42+fold.
The historical screening report is ONLY used to fix retained row identities;
every evaluation prediction is generated by a NEW CV model.

This is descriptive POST-SELECTION internal validation, not nested CV and not
a same-test-population estimate of the causal benefit of training deletion.
The evaluation fold is also used for early stopping, as in the original OOF
function. These design facts are written into every output manifest.
No PubChem-only samples or external predictions are loaded.
"""
