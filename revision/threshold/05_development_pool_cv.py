ARMS = {'no_filter': None, 'filter_5fold': 5.0, 'filter_10fold': 10.0,
        'filter_20fold': 20.0, 'filter_30fold': 30.0}
METRICS = ['R2', 'RMSE', 'MAE', 'median_fold_error', 'mean_fold_error',
           'within_2_fold_percent', 'within_5_fold_percent', 'within_10_fold_percent']
INTERPRETATION = (
    'Post-selection internal 5-fold CV of separately retained development cohorts. '
    'Selection uses the frozen full-development-pool OOF errors BEFORE evaluation '
    'folds are formed. Actual evaluation populations differ between threshold arms. '
    'The held-out evaluation fold also selects the stopping iteration, following '
    'the original OOF routine. This is NOT nested, leakage-free evaluation of the '
    'entire filtering pipeline, NOT an independent external test, and NOT a paired '
    'same-population estimate of deletion benefit. Preserve the separately completed '
    'nested and external evaluations. Do not interpret threshold-associated score '
    'changes as proof of improved data accuracy or generalization.'
)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as f:
        for b in iter(lambda: f.read(1024 * 1024), b''):
            h.update(b)
    return h.hexdigest()


def jsonable(x: Any) -> Any:
    if isinstance(x, dict):
        return {str(k): jsonable(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [jsonable(v) for v in x]
    if isinstance(x, np.ndarray):
        return jsonable(x.tolist())
    if isinstance(x, np.integer):
        return int(x)
    if isinstance(x, np.floating):
        x = float(x)
    if isinstance(x, float) and not math.isfinite(x):
        return None
    if isinstance(x, Path):
        return str(x)
    return x


def json_text(x: Any) -> str:
    return json.dumps(jsonable(x), ensure_ascii=False, sort_keys=True,
                      indent=2, allow_nan=False)


def hash_object(x: Any) -> str:
    return hashlib.sha256(json_text(x).encode('utf-8')).hexdigest()


def write_json(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + '.tmp')
    temp.write_text(json_text(obj) + '\n', encoding='utf-8')
    os.replace(temp, path)


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding='utf-8-sig'))


def write_csv(path: Path, df: pd.DataFrame) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + '.tmp')
    df.to_csv(tmp, index=False, encoding='utf-8-sig')
    os.replace(tmp, path)


def read_csv(path: Path) -> pd.DataFrame:
    return pd.read_csv(path, encoding='utf-8-sig', float_precision='round_trip')


def save_array(path: Path, arr: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + '.tmp')
    with tmp.open('wb') as f:
        np.save(f, arr, allow_pickle=False)
    os.replace(tmp, path)


def save_indices(path: Path, **arrays: np.ndarray) -> None:
    tmp = path.with_name(path.name + '.tmp')
    with tmp.open('wb') as f:
        np.savez_compressed(f, **arrays)
    os.replace(tmp, path)


def resolve_input(name: str, root: Path) -> Path:
    """Exact filename, with same-content duplicate handling; no fuzzy substitution."""
    requested = Path(name)
    direct = requested if requested.is_absolute() else root / requested
    if direct.is_file():
        return direct.resolve()
    if requested.is_absolute() or len(requested.parts) > 1:
        raise FileNotFoundError(f'Configured input not found: {direct}')
    matches = []
    for base, dirs, names in os.walk(root):
        dirs[:] = [d for d in dirs if d not in {'.git', '.venv', 'venv', '__pycache__'}
                   and not d.startswith('JHM_')]
        if requested.name in names:
            matches.append((Path(base) / requested.name).resolve())
    matches = sorted(set(matches), key=lambda p: str(p).lower())
    if not matches:
        raise FileNotFoundError(
            f'Cannot find {name} under {root}.\n'
            'Set input_report in devpool_cv_config.json to the full CSV path.\n'
            'Use the original 34,959-row train_pool_oof_residual_report.csv, '
            'NOT a nested fold report or the 34,511-row retained file.')
    if len(matches) > 1:
        if len({sha256(p) for p in matches}) != 1:
            raise RuntimeError('Different files have the same name. Select input_report explicitly:\n'
                               + '\n'.join(map(str, matches)))
        print(f'Found {len(matches)} byte-identical copies; using {matches[0]}')
    return matches[0]


def environment() -> dict:
    out = {'python': platform.python_version(), 'platform': platform.platform(),
           'rdkit': rdBase.rdkitVersion}
    for name in ['numpy', 'pandas', 'scikit-learn', 'xgboost', 'joblib', 'tqdm']:
        out[name] = importlib.metadata.version(name)
    out['xgboost_build_info'] = xgb.build_info()
    return out


def metrics(y: np.ndarray, pred: np.ndarray) -> dict:
    y, pred = np.asarray(y, dtype=np.float64), np.asarray(pred, dtype=np.float64)
    if y.ndim != 1 or pred.shape != y.shape or len(y) < 2:
        raise ValueError('Metrics require equal-length one-dimensional arrays, n>=2.')
    if not np.isfinite(y).all() or not np.isfinite(pred).all():
        raise ValueError('Nonfinite labels or predictions; no rows will be silently dropped.')
    residual = pred - y
    e = np.abs(residual)
    with np.errstate(over='ignore'):
        fe = np.power(10.0, e)
    sse = float(np.dot(residual, residual))
    sst = float(np.dot(y-y.mean(), y-y.mean()))
    return {'n': len(y), 'R2': 1.0-sse/sst if sst > 0 else None,
            'RMSE': float(np.sqrt(sse/len(y))), 'MAE': float(np.mean(e)),
            'median_fold_error': float(np.median(fe)),
            'mean_fold_error': float(np.mean(fe)),
            'within_2_fold_percent': float(np.mean(e <= np.log10(2.0))*100),
            'within_5_fold_percent': float(np.mean(e <= np.log10(5.0))*100),
            'within_10_fold_percent': float(np.mean(e <= 1.0)*100),
            'SSE': sse, 'SST': sst}


def load_inputs(cfg: dict, root: Path) -> tuple[Path, pd.DataFrame, pd.DataFrame]:
    if cfg['thresholds_fold'] != [None, 5, 10, 20, 30] or cfg['cv_folds'] != 5:
        raise ValueError('This job is fixed to no deletion + 5/10/20/30-fold error thresholds, 5 CV folds.')
    if cfg['split_seed'] != 42 or cfg['model_seed_base'] != 42:
        raise ValueError('Use the agreed original split seed 42 and fold model seeds 43..47.')
    path = resolve_input(cfg['input_report'], root)
    df = read_csv(path).reset_index(drop=True)
    required = ['Canonical SMILES', 'y', 'molecular_weight', 'source_type',
                'oof_pred_y', 'oof_fold_error']
    missing = [c for c in required if c not in df]
    if missing:
        raise ValueError(f'Missing columns: {missing}')
    if len(df) != cfg['expected_development_n']:
        raise ValueError(f'Expected {cfg["expected_development_n"]} rows; received {len(df)}.')
    if df['Canonical SMILES'].isna().any() or df['Canonical SMILES'].duplicated().any():
        raise ValueError('Missing/duplicate canonical SMILES; source file is not the expected unique-compound pool.')
    if not df['Canonical SMILES'].map(lambda x: isinstance(x, str) and bool(x.strip())).all():
        raise ValueError('SMILES must be nonempty strings.')
    if df.source_type.value_counts().to_dict() != cfg['expected_source_counts']:
        raise ValueError(f'Unexpected source counts: {df.source_type.value_counts().to_dict()}')
    for col in ['y', 'molecular_weight', 'oof_pred_y', 'oof_fold_error']:
        df[col] = pd.to_numeric(df[col], errors='raise')
        if not np.isfinite(df[col].to_numpy(float)).all():
            raise ValueError(f'Nonfinite {col}')
    if (df.molecular_weight <= 0).any() or (df.oof_fold_error < 1-1e-6).any():
        raise ValueError('Invalid molecular weights or fold errors.')
    if 'ld50_mgkg' in df:
        ld = df.ld50_mgkg.to_numpy(float)
        if not np.isfinite(ld).all() or (ld <= 0).any():
            raise ValueError('Invalid ld50_mgkg')
        check_y = -np.log10(ld / 1000.0 / df.molecular_weight.to_numpy(float))
        if not np.allclose(check_y, df.y, rtol=0, atol=2e-6):
            raise ValueError('Target does not match -log10(LD50 in mol/kg).')
    check_fe = 10.0 ** np.abs(df.y.to_numpy(float)-df.oof_pred_y.to_numpy(float))
    if not np.allclose(check_fe, df.oof_fold_error, rtol=1e-6, atol=1e-6):
        raise ValueError('Saved full-pool OOF errors do not match labels/predictions.')
    hist = metrics(df.y.to_numpy(float), df.oof_pred_y.to_numpy(float))
    for key, expected in {'R2': 0.6541696786880493, 'RMSE': 0.39191964185711403,
                          'MAE': 0.2630552649497986}.items():
        if abs(hist[key]-expected) > 2e-6:
            raise ValueError(f'Historical screening {key} mismatch; do not use nested reports.')
    for t in [5, 10, 20, 30]:
        n_removed = int((df.oof_fold_error >= t).sum())
        if n_removed != cfg['expected_removed_counts'][str(t)]:
            raise ValueError(f'{t}-fold threshold removes {n_removed}, inconsistent with original report.')
    if len(core.RDKit_2D_DESC_LIST) + core.ECFP_BITS != cfg['expected_raw_feature_dim']:
        raise ValueError('Local descriptor registry does not match the expected 2,265 raw features. '
                         'Do not automatically add/drop descriptors; check the training environment.')
    bad = []
    for i, smi in enumerate(df['Canonical SMILES']):
        if Chem.MolFromSmiles(smi) is None:
            bad.append(i)
            if len(bad) >= 10:
                break
    if bad:
        raise ValueError(f'Invalid standardized SMILES at pool rows {bad}; no auto-deletion.')
    if 'pool_row_id' in df:
        raise ValueError('Input already has a reserved pool_row_id column.')
    df.insert(0, 'pool_row_id', np.arange(len(df), dtype=np.int64))
    design = []
    for arm, threshold in ARMS.items():
        n_rem = 0 if threshold is None else int((df.oof_fold_error >= threshold).sum())
        design.append({'arm': arm, 'threshold_fold': threshold,
                       'n_initial_development': len(df), 'n_removed': n_rem,
                       'n_evaluation_cohort': len(df)-n_rem,
                       'removed_percent': n_rem/len(df)*100,
                       'evaluation_cv_folds': 5,
                       'screening_scope': 'whole_development_pool_before_CV',
                       'validation_fold_used_for_early_stopping': True,
                       'nested_screening': False})
    return path, df, pd.DataFrame(design)


def cohort_rows(df: pd.DataFrame, threshold: float | None) -> np.ndarray:
    mask = np.ones(len(df), dtype=bool) if threshold is None else (
        df.oof_fold_error.to_numpy(float) < threshold)
    return np.flatnonzero(mask).astype(np.int64)


def cohort_splits(rows: np.ndarray, seed: int = 42) -> list[tuple[np.ndarray, np.ndarray]]:
    kf = KFold(n_splits=5, shuffle=True, random_state=seed)
    splits = [(rows[tr], rows[va]) for tr, va in kf.split(rows)]
    all_val = np.concatenate([va for _, va in splits])
    if not np.array_equal(np.sort(all_val), rows):
        raise AssertionError('Each retained compound must be evaluated once.')
    for tr, va in splits:
        if np.intersect1d(tr, va).size:
            raise AssertionError('Train/evaluation overlap in CV fold.')
    return splits


def raw_features(df: pd.DataFrame, run: Path, expected_dim: int) -> np.ndarray:
    p = run / 'cache' / 'raw_features.npy'
    meta = p.with_suffix('.json')
    if p.exists() and meta.exists():
        m = read_json(meta)
        if m['sha256'] != sha256(p):
            raise RuntimeError('Feature cache checksum mismatch; remove only this run cache and retry.')
        arr = np.load(p, mmap_mode='r', allow_pickle=False)
        if arr.shape != (len(df), expected_dim) or arr.dtype != np.float32:
            raise RuntimeError('Unexpected cached feature shape/dtype.')
        print('Reusing this run\'s raw-feature cache.')
        return arr
    print('Calculating original ECFP4-count log1p + RDKit 2D features (once per run).')
    arr = core.build_raw_features(df, 'full_development_pool')
    if arr.shape != (len(df), expected_dim):
        raise ValueError(f'Unexpected raw feature shape {arr.shape}')
    save_array(p, arr)
    write_json(meta, {'shape': list(arr.shape), 'dtype': str(arr.dtype), 'sha256': sha256(p)})
    del arr
    gc.collect()
    return np.load(p, mmap_mode='r', allow_pickle=False)


def save_cohort_files(df: pd.DataFrame, rows: np.ndarray, splits: list, arm_dir: Path) -> None:
    arm_dir.mkdir(parents=True, exist_ok=True)
    keep = np.zeros(len(df), dtype=bool)
    keep[rows] = True
    write_csv(arm_dir / 'retained_compounds.csv', df.loc[keep])
    write_csv(arm_dir / 'removed_compounds.csv', df.loc[~keep])
    assignments = df.loc[rows, ['pool_row_id', 'Canonical SMILES', 'source_type', 'y']].copy()
    lookup = np.zeros(len(df), dtype=np.int16)
    for f, (_, va) in enumerate(splits, 1):
        lookup[va] = f
    assignments['evaluation_fold'] = lookup[rows]
    write_csv(arm_dir / 'cv_fold_assignments.csv', assignments)


def checked_checkpoint(folder: Path, run_id: str, arm: str, fold: int,
                       tr: np.ndarray, va: np.ndarray) -> dict | None:
    p = folder / 'done.json'
    if not p.exists():
        return None
    done = read_json(p)
    if (done.get('run_id'), done.get('arm'), done.get('fold')) != (run_id, arm, fold):
        raise RuntimeError(f'Checkpoint identity mismatch: {folder}')
    for name, digest in done['artifacts'].items():
        target = folder / name
        if not target.is_file() or sha256(target) != digest:
            raise RuntimeError(f'Checkpoint artifact missing/corrupted: {target}')
    with np.load(folder / 'split_indices.npz', allow_pickle=False) as idx:
        if not np.array_equal(idx['train_pool_rows'], tr) or not np.array_equal(idx['evaluation_pool_rows'], va):
            raise RuntimeError(f'Checkpoint split mismatch: {folder}')
    return done


def run_fold(df: pd.DataFrame, X_raw: np.ndarray, tr: np.ndarray, va: np.ndarray,
             cfg: dict, folder: Path, run_id: str, arm: str, fold: int) -> None:
    done = checked_checkpoint(folder, run_id, arm, fold, tr, va)
    if done is not None:
        print(f'[RESUME] {arm}, fold {fold} already completed and checksum-verified.')
        return
    folder.mkdir(parents=True, exist_ok=True)
    seed = cfg['model_seed_base'] + fold
    random.seed(seed)
    np.random.seed(seed)
    params = dict(cfg['xgboost_params'])
    params['seed'] = seed
    print(f'\n===== {arm} | CV fold {fold}/5 | train={len(tr)} | evaluation={len(va)} | seed={seed} =====')
    save_indices(folder / 'split_indices.npz', train_pool_rows=tr, evaluation_pool_rows=va)
    write_json(folder / 'fit_request.json', {
        'run_id': run_id, 'arm': arm, 'fold': fold, 'parameters': params,
        'max_boost_rounds': cfg['max_boost_rounds'],
        'early_stopping_rounds': cfg['early_stopping_rounds'],
        'early_stopping_set': 'same_as_evaluation_fold_original_protocol',
        'training_n': len(tr), 'evaluation_n': len(va), 'interpretation': INTERPRETATION})
    Xtr_raw = X_raw[tr]
    Xva_raw = X_raw[va]
    core.OUTPUT_DIR = str(folder)
    (Xtr, Xva), prep = core.fit_preprocess_and_transform(
        Xtr_raw, [Xtr_raw, Xva_raw], save_prefix='fold')
    # Original preprocessor does not save this mask; saving it changes no numbers.
    keep_cols = ~np.all(np.isnan(np.where(np.isfinite(Xtr_raw), Xtr_raw, np.nan)), axis=0)
    save_array(folder / 'fold_non_all_nan_columns.npy', keep_cols)
    del Xtr_raw, Xva_raw
    gc.collect()
    ytr = df.y.to_numpy(dtype=np.float32)[tr]
    yva = df.y.to_numpy(dtype=np.float32)[va]
    booster, best_iter = core.train_with_early_stopping(params, Xtr, ytr, Xva, yva)
    pred = booster.predict(xgb.DMatrix(Xva), iteration_range=(0, best_iter))
    pred = np.asarray(pred, dtype=np.float32)
    if pred.shape != (len(va),) or not np.isfinite(pred).all():
        raise RuntimeError('Invalid new CV predictions.')
    # Use original stored labels at reporting precision; model training used float32.
    y64 = df.y.to_numpy(dtype=float)[va]
    m = metrics(y64, pred)
    conf = json.loads(booster.save_config())
    write_json(folder / 'trained_booster_config.json', conf)
    actual_device = conf.get('learner', {}).get('generic_param', {}).get('device', 'unavailable')
    with np.errstate(over='ignore'):
        fe = 10.0 ** np.abs(pred.astype(float)-y64)
    prediction = df.loc[va, ['pool_row_id','Canonical SMILES','source_type','molecular_weight']].copy()
    prediction['arm'] = arm
    prediction['evaluation_fold'] = fold
    prediction['y_true_neglog_molkg'] = y64
    prediction['y_pred_neglog_molkg'] = pred
    prediction['fold_error'] = fe
    write_csv(folder / 'validation_predictions.csv', prediction)
    metadata = {'run_id': run_id, 'arm': arm, 'fold': fold, 'model_seed': seed,
                'n_train': len(tr), 'n_evaluation': len(va), 'best_iteration_count': int(best_iter),
                'trained_round_count': int(booster.num_boosted_rounds()),
                'actual_device': actual_device, 'preprocessing': prep, 'metrics': m,
                'completed_utc': datetime.now(timezone.utc).isoformat(),
                'validation_fold_used_for_early_stopping': True,
                'screening_before_evaluation_cv': True}
    if cfg['save_models']:
        # .ubj selects the current XGBoost serialization format.
        booster.save_model(folder / 'model.ubj')
    names = ['split_indices.npz', 'fit_request.json', 'validation_predictions.csv',
             'trained_booster_config.json', 'fold_imputer.joblib',
             'fold_variance_selector.joblib', 'fold_feature_preprocess_info.json',
             'fold_non_all_nan_columns.npy']
    if cfg['save_models']:
        names.append('model.ubj')
    metadata['artifacts'] = {name: sha256(folder/name) for name in names}
    write_json(folder / 'done.json', metadata)  # Commit only after complete artifact writes.
    print(f'Finished {arm} fold {fold}: R2={m["R2"]:.6f}, RMSE={m["RMSE"]:.6f}, MAE={m["MAE"]:.6f}')
    del booster, Xtr, Xva, ytr, yva
    gc.collect()


def aggregate(df: pd.DataFrame, cfg: dict, design: pd.DataFrame, run: Path, run_id: str) -> None:
    folds_out, pooled_out, summary_out, comparison = [], [], [], []
    for design_row in design.to_dict('records'):
        arm = design_row['arm']
        rows = cohort_rows(df, ARMS[arm])
        splits = cohort_splits(rows, cfg['split_seed'])
        parts, arm_fold_metrics = [], []
        for fold, (tr, va) in enumerate(splits, 1):
            folder = run / arm / f'fold_{fold}'
            done = checked_checkpoint(folder, run_id, arm, fold, tr, va)
            if done is None:
                continue
            p = read_csv(folder / 'validation_predictions.csv')
            if not np.array_equal(p.pool_row_id.to_numpy(np.int64), va):
                raise RuntimeError('Prediction row order differs from committed evaluation split.')
            if not np.allclose(p.y_true_neglog_molkg, df.y.to_numpy(float)[va], rtol=0, atol=1e-12):
                raise RuntimeError('Prediction labels differ from source labels.')
            if not np.array_equal(p['Canonical SMILES'].to_numpy(), df['Canonical SMILES'].to_numpy()[va]):
                raise RuntimeError('Prediction SMILES differ from source rows.')
            m = metrics(p.y_true_neglog_molkg.to_numpy(), p.y_pred_neglog_molkg.to_numpy())
            row = {'arm': arm, 'threshold_fold': ARMS[arm], 'fold': fold,
                   'model_seed': done['model_seed'], 'n_train': len(tr),
                   'best_iteration_count': done['best_iteration_count'],
                   'actual_device': done['actual_device'], **m}
            folds_out.append(row)
            arm_fold_metrics.append(row)
            parts.append(p)
        n_folds = len(parts)
        is_complete = n_folds == 5
        basic = {**design_row, 'folds_completed': n_folds, 'complete': is_complete,
                 'evaluation_role': 'post_selection_internal_CV'}
        pooled = {**basic, 'n_predicted': sum(len(p) for p in parts)}
        sm = basic.copy()
        # Do not label a partial subset as the full pooled result.
        if is_complete:
            joined = pd.concat(parts, ignore_index=True).sort_values('pool_row_id').reset_index(drop=True)
            if not np.array_equal(joined.pool_row_id.to_numpy(np.int64), rows):
                raise RuntimeError('Completed arm is missing/duplicating retained compounds.')
            m = metrics(joined.y_true_neglog_molkg.to_numpy(), joined.y_pred_neglog_molkg.to_numpy())
            pooled.update(m)
            for key in METRICS:
                vals = np.asarray([d[key] for d in arm_fold_metrics], dtype=float)
                sm[f'mean_{key}'] = float(vals.mean())
                sm[f'sd_{key}'] = float(vals.std(ddof=1))
            write_csv(run / arm / 'cv_oof_predictions.csv', joined)
        pooled_out.append(pooled)
        summary_out.append(sm)
        comp = {**basic, 'n_predicted': pooled['n_predicted']}
        for key in ['R2', 'RMSE', 'MAE', 'median_fold_error', 'within_2_fold_percent']:
            comp[f'pooled_{key}'] = pooled.get(key)
            comp[f'fold_mean_{key}'] = sm.get(f'mean_{key}')
            comp[f'fold_sd_{key}'] = sm.get(f'sd_{key}')
        comparison.append(comp)
    write_csv(run / 'development_cv_fold_results.csv', pd.DataFrame(folds_out))
    write_csv(run / 'development_cv_pooled_results.csv', pd.DataFrame(pooled_out))
    write_csv(run / 'development_cv_mean_sd.csv', pd.DataFrame(summary_out))
    write_csv(run / 'development_cv_comparison.csv', pd.DataFrame(comparison))
    write_json(run / 'progress.json', {'run_id': run_id,
               'all_arms_complete': all(x['complete'] for x in comparison),
               'completed_fits': len(folds_out), 'planned_fits': 25,
               'updated_utc': datetime.now(timezone.utc).isoformat(),
               'interpretation': INTERPRETATION})


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', default=str(ROOT/'devpool_cv_config.json'))
    parser.add_argument('--preflight-only', action='store_true', help='No feature matrix or model training.')
    parser.add_argument('--summarize-only', action='store_true', help='Recalculate summaries from completed predictions; no training.')
    args = parser.parse_args(argv)
    config_path = Path(args.config).resolve()
    cfg = read_json(config_path)
    root = config_path.parent
    path, df, design = load_inputs(cfg, root)
    env = environment()
    source_hashes = {p.name: sha256(p) for p in [Path(__file__), Path(core.__file__)]}
    descriptor_names = [name for name, _ in core.RDKit_2D_DESC_LIST]
    signature = {'config': cfg, 'input_sha256': sha256(path), 'source_hashes': source_hashes,
                 'environment': env, 'descriptor_names': descriptor_names,
                 'protocol': INTERPRETATION}
    run_id = hash_object(signature)[:16]
    out = Path(cfg['output_folder'])
    out = out if out.is_absolute() else root/out
    run = out/f'run_{run_id}'
    print('\nInput:', path)
    print('Output:', run)
    print('Development compounds:', len(df), '| sources:', df.source_type.value_counts().to_dict())
    print('Thresholds are ERROR MULTIPLES, not numbers of CV folds.')
    print(design[['arm','threshold_fold','n_initial_development','n_removed','n_evaluation_cohort']].to_string(index=False))
    print('Each arm: NEW five-fold CV; model seeds 43,44,45,46,47; max rounds', cfg['max_boost_rounds'])
    print('Early stopping:', cfg['early_stopping_rounds'], 'rounds; evaluation fold also used for stopping, as in original code.')
    print('No PubChem-only input. This is post-selection internal CV, NOT nested validation.')
    run.mkdir(parents=True, exist_ok=True)
    manifest_path = run/'manifest.json'
    if manifest_path.exists():
        if read_json(manifest_path)['signature'] != jsonable(signature):
            raise RuntimeError('Run-manifest collision/mismatch; refusing to reuse results.')
    else:
        write_json(manifest_path, {'run_id': run_id, 'signature': signature,
                   'input_path': str(path), 'created_utc': datetime.now(timezone.utc).isoformat(),
                   'input_used_for_training': 'SMILES-derived features and y only; no OOF error feature',
                   'screening_report_reused': True, 'fresh_evaluation_predictions': True,
                   'external_evaluation_performed': False, 'same_test_population_between_arms': False,
                   'final_model_ensemble': False, 'historical_environment_identity_guaranteed': False})
    write_csv(run/'screening_cohort_sizes.csv', design)
    write_json(run/'resolved_config.json', cfg)
    write_json(run/'feature_definition.json', {
        'fingerprint': 'Morgan ECFP4 count, radius=2, fpSize=2048, includeChirality default False, log1p',
        'rdkit_descriptor_names': descriptor_names,
        'all_raw_feature_names': [f'ECFP4_count_log1p_{j}' for j in range(2048)]+[f'RDKit2D_{n}' for n in descriptor_names],
        'raw_dim': 2048+len(descriptor_names), 'rdkit_version': rdBase.rdkitVersion})
    (run/'interpretation_notes.txt').write_text(INTERPRETATION+'\n', encoding='utf-8')
    write_json(run/'preflight.json', {'passed': True, 'training_started': False,
               'run_id': run_id, 'input': str(path), 'input_rows': len(df),
               'expected_20fold_removed': 448, 'all_cv_folds': 5,
               'planned_evaluation_model_fits': 25,
               'gpu_execution_not_tested_by_preflight': True})
    if args.preflight_only:
        print('\nPREFLIGHT PASSED. No models were trained. Run 05_development_pool_cv.py next.')
        return
    if args.summarize_only:
        aggregate(df, cfg, design, run, run_id)
        print('Summary files refreshed without training.')
        return
    core.NUM_BOOST_ROUND = int(cfg['max_boost_rounds'])
    core.EARLY_STOPPING_ROUNDS = int(cfg['early_stopping_rounds'])
    X_raw = raw_features(df, run, cfg['expected_raw_feature_dim'])
    for arm, threshold in ARMS.items():
        rows = cohort_rows(df, threshold)
        splits = cohort_splits(rows, cfg['split_seed'])
        save_cohort_files(df, rows, splits, run/arm)
        for fold, (tr, va) in enumerate(splits, 1):
            run_fold(df, X_raw, tr, va, cfg, run/arm/f'fold_{fold}', run_id, arm, fold)
            aggregate(df, cfg, design, run, run_id)
    print('\nALL 25 CV FITS COMPLETED.')
    result = read_csv(run/'development_cv_comparison.csv')
    print(result[['arm','n_evaluation_cohort','complete','pooled_R2','pooled_RMSE','pooled_MAE']].to_string(index=False))
    print('\nResult file:', run/'development_cv_comparison.csv')
    print('Compare new results only under their stated post-selection internal-CV scope. No threshold is automatically selected.')


